# Explainability view  (loads Phase 6 JSON – no re-computation)
# ---------------------------------------------------------------------------
def render_explainability():
    st.markdown("## 🔬 Model Explainability (Phase 6 Results)")

    expl = load_explainability()
    if not expl:
        st.warning(f"Explainability JSON not found at `{EXPL_PATH}`.")
        return

    metrics = load_metrics()

    # Model performance summary
    if metrics:
        bm = metrics.get("best_model", {})
        model_name = bm.get("name", "Logistic Regression")
        val_auc    = bm.get("val_roc_auc", "—")
        st.info(
            f"**Best model:** {model_name}  ·  "
            f"**Validation ROC-AUC:** {val_auc}  ·  "
            f"Selection criterion: {bm.get('selection_criterion', '—')}"
        )

    tab1, tab2, tab3, tab4 = st.tabs(
        ["SHAP Global (G5)", "Permutation (G4)", "LR Coefficients (G1)", "Local Cases (L1)"]
    )

    # --- G5 SHAP ---
    with tab1:
        st.markdown("### SHAP Mean |Value| — Global Feature Importance (RF)")
        shap_data = pd.DataFrame(expl.get("g5_shap_mean_abs", []))
        if not shap_data.empty:
            shap_data = shap_data.sort_values("mean_abs_shap", ascending=True).tail(20)
            fig = go.Figure(go.Bar(
                x=shap_data["mean_abs_shap"],
                y=shap_data["feature"],
                orientation="h",
                marker_color=CLR_GREEN,
                text=shap_data["mean_abs_shap"].apply(lambda v: f"{v:.5f}"),
                textposition="outside",
            ))
            fig.update_layout(
                height=520, plot_bgcolor=CLR_BG, paper_bgcolor="white",
                margin=dict(l=0, r=80, t=10, b=10),
                xaxis_title="Mean |SHAP value|",
            )
            st.plotly_chart(fig, use_container_width=True)
        st.caption(
            "⚠️ **Association, not causation.** SHAP values describe what the model "
            "learned from training data — not causal relationships between features and conversion."
        )

    # --- G4 Permutation ---
    with tab2:
        st.markdown("### Permutation Importance — ROC-AUC Drop (15 repeats, RF test set)")
        perm_data = pd.DataFrame(expl.get("g4_permutation_importance", []))
        if not perm_data.empty:
            perm_data = perm_data.sort_values("mean_drop", ascending=True)
            colors    = [CLR_GREEN if v > 0.001 else CLR_RED if v < -0.001
                         else CLR_MUTED for v in perm_data["mean_drop"]]
            fig = go.Figure(go.Bar(
                x=perm_data["mean_drop"],
                y=perm_data["feature"],
                orientation="h",
                marker_color=colors,
                error_x=dict(type="data", array=perm_data["std_drop"].tolist(),
                             color="#374151", thickness=1.2),
                text=perm_data["mean_drop"].apply(lambda v: f"{v:+.5f}"),
                textposition="outside",
            ))
            fig.add_vline(x=0, line_dash="dash", line_color="#374151")
            fig.update_layout(
                height=360, plot_bgcolor=CLR_BG, paper_bgcolor="white",
                margin=dict(l=0, r=90, t=10, b=10),
                xaxis_title="Mean ROC-AUC drop (positive = model degrades when shuffled)",
            )
            st.plotly_chart(fig, use_container_width=True)
        st.caption(
            "⚠️ All values are within ±0.01 of zero — no feature provides genuine "
            "predictive lift beyond random chance (ROC-AUC ≈ 0.50–0.51). "
            "See Phase 7 recommendations for required additional features."
        )

    # --- G1 LR Coefficients ---
    with tab3:
        st.markdown("### Logistic Regression Signed Coefficients (Best Model)")
        lr_data = pd.DataFrame(expl.get("g1_lr_coefficients", []))
        if not lr_data.empty:
            lr_data = lr_data.sort_values("coefficient", ascending=True)
            colors  = [CLR_RED if v < 0 else CLR_GREEN for v in lr_data["coefficient"]]
            fig = go.Figure(go.Bar(
                x=lr_data["coefficient"],
                y=lr_data["feature"],
                orientation="h",
                marker_color=colors,
                text=lr_data["coefficient"].apply(lambda v: f"{v:+.4f}"),
                textposition="outside",
            ))
            fig.add_vline(x=0, line_color="#374151")
            fig.update_layout(
                height=680, plot_bgcolor=CLR_BG, paper_bgcolor="white",
                margin=dict(l=0, r=80, t=10, b=10),
                xaxis_title="Coefficient (positive → model predicts Won)",
            )
            st.plotly_chart(fig, use_container_width=True)
        st.caption(
            "⚠️ Max |coefficient| < 0.04 — all coefficients are near-zero, "
            "confirming the model has essentially not learned a meaningful signal."
        )

    # --- L1 Local Cases ---
    with tab4:
        st.markdown("### SHAP Waterfall — Representative Individual Predictions")
        cases = expl.get("l1_local_cases", {})
        case_meta = {
            "tp": ("✅ True Positive",  "High prob · Actual = Won",      CLR_GREEN),
            "fp": ("❌ False Positive", "High prob · Actual = Not Won",   CLR_RED),
            "fn": ("⚠️ False Negative", "Low prob  · Actual = Won",      CLR_AMBER),
            "tn": ("✓  True Negative",  "Low prob  · Actual = Not Won",  CLR_BLUE),
        }
        for key, (label, subtitle, color) in case_meta.items():
            c = cases.get(key, {})
            if not c:
                continue
            with st.expander(f"{label}  —  {subtitle}  |  Pred={c['predicted_prob']:.4f}  |  Actual={c['actual_label']}"):
                feats = pd.DataFrame(c.get("top_shap_features", []))
                if feats.empty:
                    continue
                feats = feats.sort_values("shap_value", ascending=True)
                bar_colors = [CLR_GREEN if v > 0 else CLR_RED for v in feats["shap_value"]]
                fig = go.Figure(go.Bar(
                    x=feats["shap_value"],
                    y=feats["feature"],
                    orientation="h",
                    marker_color=bar_colors,
                    text=feats["shap_value"].apply(lambda v: f"{v:+.4f}"),
                    textposition="outside",
                ))
                fig.add_vline(x=0, line_color="#374151")
                fig.update_layout(
                    height=320, plot_bgcolor=CLR_BG, paper_bgcolor="white",
                    margin=dict(l=0, r=80, t=10, b=10),
                    xaxis_title="SHAP value (contribution to predicted probability)",
                    title=dict(text=f"{label}  ·  Predicted prob = {c['predicted_prob']:.4f}",
                               font_size=12),
                )
                st.plotly_chart(fig, use_container_width=True)

        cbs = expl.get("causal_boundary_statement", {})
        if cbs:
            st.markdown("---")
