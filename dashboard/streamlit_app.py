def render_scorer(full_df: pd.DataFrame):
    st.markdown("## 🎯 What-If Lead Scorer")
    st.caption(
        "Adjust lead attributes to score them live with the trained Phase 5 pipeline.  \n"
        "The model outputs a probability calibrated against the training distribution."
    )

    total, owner_counts, company_counts = compute_freq_tables(full_df)

    sources       = sorted(full_df["source"].dropna().unique())
    source_groups = sorted(full_df["source_group"].dropna().unique())

    col_form, col_result = st.columns([2, 1])

    with col_form:
        with st.form("what_if_scorer", border=True):
            st.markdown("#### Lead Attributes")
            r1c1, r1c2 = st.columns(2)
            score_source = r1c1.selectbox("Lead Source", sources, index=0)
            score_group  = r1c2.selectbox(
                "Source Group", source_groups,
                index=source_groups.index("Inbound") if "Inbound" in source_groups else 0,
            )

            r2c1, r2c2 = st.columns(2)
            # Owner: free text (frequency-encoded at score time)
            score_owner   = r2c1.text_input("Lead Owner", value="Alice Johnson")
            company_name  = r2c2.text_input("Company", value="Acme Corp")

            st.markdown("#### Notes Features")
            r3c1, r3c2, r3c3 = st.columns(3)
            notes_sentiment  = r3c1.slider(
                "Sentiment", min_value=-1.0, max_value=1.0, value=0.20, step=0.05,
                help="TextBlob polarity. 0 = neutral.",
            )
            notes_word_count = r3c2.number_input(
                "Word Count", min_value=0, max_value=5000, value=120,
                help="Number of words in the lead notes.",
            )
            notes_has_text = r3c3.checkbox("Has Text", value=True)

            submitted = st.form_submit_button("▶  Score Lead", use_container_width=True)

    with col_result:
        st.markdown("#### Prediction")
        if not submitted:
            st.info("Fill in the form and click **Score Lead**.")
        else:
            try:
                model = load_model()
            except (FileNotFoundError, OSError) as err:
                st.error(f"Cannot load model: {err}")
                return

            vec = build_vector(
                source=score_source,
                source_group=score_group,
                notes_sentiment=notes_sentiment,
                notes_word_count=int(notes_word_count),
                notes_has_text=1 if notes_has_text else 0,
                lead_owner=score_owner,
                company=company_name,
                owner_counts=owner_counts,
                company_counts=company_counts,
                total=total,
            )

            try:
                prob   = float(model.predict_proba([vec])[0, 1])
                label  = "Likely Won" if prob >= 0.5 else "Likely Lost"
                colour = CLR_GREEN if prob >= 0.5 else CLR_RED
            except Exception as err:
                st.error(f"Scoring error: {err}")
                return

            # Gauge chart
            fig_gauge = go.Figure(go.Indicator(
                mode="gauge+number+delta",
                value=prob * 100,
                delta={"reference": 9.99, "suffix": " pp vs base rate"},
                number={"suffix": "%", "font": {"size": 36}},
                gauge={
                    "axis": {"range": [0, 100], "tickwidth": 1},
                    "bar":  {"color": colour},
                    "steps": [
                        {"range": [0, 30],  "color": "#fee2e2"},
                        {"range": [30, 50], "color": "#fef3c7"},
                        {"range": [50, 100],"color": "#dcfce7"},
                    ],
                    "threshold": {
                        "line": {"color": "#374151", "width": 2},
                        "thickness": 0.8, "value": 50,
                    },
                },
                title={"text": label, "font": {"size": 18, "color": colour}},
            ))
            fig_gauge.update_layout(
                height=260, margin=dict(l=10, r=10, t=30, b=10),
                paper_bgcolor="white",
            )
            st.plotly_chart(fig_gauge, use_container_width=True)

            st.metric("Win Probability", f"{prob * 100:.2f}%")
            st.metric("Prediction Class", label)

            tier = SOURCE_TIER.get(score_source, 2)
            tier_label = {1: "Tier 1 (High)", 2: "Tier 2 (Mid)", 3: "Tier 3 (Low)"}[tier]
            st.caption(f"Source tier: **{tier_label}**")

    # Feature contribution breakdown
    if submitted:
        st.markdown("---")
        st.markdown("#### Feature Contribution Breakdown")
        st.caption(
            "Approximate contribution of each feature group to the predicted score, "
            "based on the Phase 6 SHAP ranking (ordering only — not per-sample SHAP)."
        )

        expl     = load_explainability()
        shap_map = {
            row["feature"]: row["mean_abs_shap"]
            for row in expl.get("g5_shap_mean_abs", [])
        }

        # Build approximate feature-contribution display
        feature_display = [
            ("Lead Source",    score_source,              shap_map.get("source_tier", 0.002668)),
            ("Source Group",   score_group,               shap_map.get("source_group_Inbound", 0.001789)),
            ("Notes Sentiment",f"{notes_sentiment:+.2f}", shap_map.get("notes_sentiment", 0.005179)),
            ("Notes Word Count",str(notes_word_count),    shap_map.get("notes_word_count", 0.005713)),
            ("Company Freq",   company_name,              shap_map.get("company_freq", 0.004284)),
            ("Owner Freq",     score_owner,               shap_map.get("owner_freq", 0.001753)),
        ]
        contrib_df = pd.DataFrame(
            feature_display, columns=["Feature Group", "Value", "Global Importance (mean|SHAP|)"]
        ).sort_values("Global Importance (mean|SHAP|)", ascending=True)

        fig_contrib = go.Figure(go.Bar(
            x=contrib_df["Global Importance (mean|SHAP|)"],
            y=contrib_df["Feature Group"],
            orientation="h",
            marker_color=CLR_BLUE,
            text=contrib_df["Value"],
            textposition="outside",
        ))
        fig_contrib.update_layout(
            height=280, plot_bgcolor=CLR_BG, paper_bgcolor="white",
            margin=dict(l=0, r=160, t=10, b=10),
            xaxis_title="Global SHAP importance (mean |SHAP|)",
        )
        st.plotly_chart(fig_contrib, use_container_width=True)
        st.caption(
            "⚠️ These are **global** importances from Phase 6 — not per-sample SHAP values. "
            "The model ROC-AUC is ~0.51 (near-random); scores should be interpreted as "
            "directional associations, not precise predictions."
        )


