# Overview view
# ---------------------------------------------------------------------------
def render_overview(filtered: pd.DataFrame):
    st.markdown("## 📋 Overview")

    # --- Deal-stage funnel ---
    stage_counts = (
        filtered["deal_stage"]
        .value_counts()
        .reindex([s for s in STAGE_ORDER if s in filtered["deal_stage"].unique()])
        .fillna(0)
        .astype(int)
        .reset_index()
    )
    stage_counts.columns = ["Deal Stage", "Count"]

    col_left, col_right = st.columns(2)

    with col_left:
        st.markdown("### Deal Stage Distribution")
        fig_funnel = go.Figure(go.Bar(
            x=stage_counts["Count"],
            y=stage_counts["Deal Stage"],
            orientation="h",
            marker_color=CLR_BLUE,
            text=stage_counts["Count"].apply(lambda v: f"{v:,}"),
            textposition="outside",
        ))
        fig_funnel.update_layout(
            margin=dict(l=0, r=40, t=10, b=10),
            height=380,
            plot_bgcolor=CLR_BG,
            paper_bgcolor="white",
            xaxis_title="Lead Count",
            yaxis=dict(autorange="reversed"),
        )
        st.plotly_chart(fig_funnel, use_container_width=True)

    # --- Source win-rate bar ---
    with col_right:
        st.markdown("### Win Rate by Lead Source")
        src_summary = (
            filtered.groupby("source", as_index=False)
            .agg(Leads=("source", "size"), Won=("is_won", "sum"))
        )
        src_summary["Win Rate %"] = (src_summary["Won"] / src_summary["Leads"] * 100).round(2)
        src_summary = src_summary.sort_values("Win Rate %", ascending=True)

        fig_rate = go.Figure(go.Bar(
            x=src_summary["Win Rate %"],
            y=src_summary["source"],
            orientation="h",
            marker=dict(
                color=src_summary["Win Rate %"],
                colorscale=[[0, "#fee2e2"], [0.5, CLR_BLUE], [1, CLR_GREEN]],
                showscale=False,
            ),
            text=src_summary["Win Rate %"].apply(lambda v: f"{v:.1f}%"),
            textposition="outside",
        ))
        fig_rate.update_layout(
            margin=dict(l=0, r=50, t=10, b=10),
            height=380,
            plot_bgcolor=CLR_BG,
            paper_bgcolor="white",
            xaxis_title="Win Rate (%)",
            yaxis=dict(autorange="reversed"),
        )
        st.plotly_chart(fig_rate, use_container_width=True)

    # --- Source volume vs conversion scatter ---
    st.markdown("### Lead Volume vs Conversion Rate by Source")
    src_bubble = (
        filtered.groupby("source", as_index=False)
        .agg(Leads=("source", "size"), Won=("is_won", "sum"))
    )
    src_bubble["Win Rate %"] = (src_bubble["Won"] / src_bubble["Leads"] * 100).round(2)

    fig_scatter = px.scatter(
        src_bubble,
        x="Leads", y="Win Rate %",
        text="source",
        size="Leads",
        color="Win Rate %",
        color_continuous_scale=[[0, "#fee2e2"], [0.5, CLR_BLUE], [1, CLR_GREEN]],
        labels={"Leads": "Lead Volume", "Win Rate %": "Win Rate (%)"},
    )
    fig_scatter.update_traces(textposition="top center", textfont_size=10)
    fig_scatter.update_layout(
        height=420,
        plot_bgcolor=CLR_BG,
        paper_bgcolor="white",
        margin=dict(l=0, r=0, t=10, b=10),
        coloraxis_showscale=False,
    )
    st.plotly_chart(fig_scatter, use_container_width=True)

    # --- Sentiment distribution by outcome ---
    st.markdown("### Notes Sentiment Distribution by Outcome")
    sent_df = filtered[["notes_sentiment", "is_won"]].copy()
    sent_df["Outcome"] = sent_df["is_won"].map({1: "Won", 0: "Not Won"})

    fig_sent = px.histogram(
        sent_df, x="notes_sentiment", color="Outcome",
        nbins=40, barmode="overlay", opacity=0.65,
        color_discrete_map={"Won": CLR_GREEN, "Not Won": CLR_RED},
        labels={"notes_sentiment": "Notes Sentiment (TextBlob polarity)"},
    )
    fig_sent.update_layout(
        height=280, plot_bgcolor=CLR_BG, paper_bgcolor="white",
        margin=dict(l=0, r=0, t=10, b=10),
    )
    st.plotly_chart(fig_sent, use_container_width=True)


