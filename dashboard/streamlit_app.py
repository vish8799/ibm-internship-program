@st.cache_data(show_spinner=False)
def compute_freq_tables(df: pd.DataFrame) -> tuple[int, dict, dict]:
    total = len(df)
    owner_counts   = df["lead_owner"].value_counts().to_dict()
    company_counts = df["company"].value_counts().to_dict()
    return total, owner_counts, company_counts


# ---------------------------------------------------------------------------
# Feature vector builder (mirrors Phase 5 / Phase 6 exactly)
# ---------------------------------------------------------------------------
def build_vector(
    source: str, source_group: str,
    notes_sentiment: float, notes_word_count: int,
    notes_has_text: int, lead_owner: str, company: str,
    owner_counts: dict, company_counts: dict, total: int,
) -> list:
    return [
        source,
        source_group,
        float(notes_sentiment),
        int(notes_word_count),
        int(notes_has_text),
        SOURCE_TIER.get(source, 2),
        owner_counts.get(lead_owner, 0) / total,
        company_counts.get(company, 0) / total,
    ]


