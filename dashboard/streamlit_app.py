# Sidebar – filters & navigation
# ---------------------------------------------------------------------------
def render_sidebar(df: pd.DataFrame):
    with st.sidebar:
        st.image(
            "https://upload.wikimedia.org/wikipedia/commons/5/51/IBM_logo.svg",
            width=80,
        )
        st.markdown("## Lead Intelligence")
        st.markdown("---")

        view = st.radio(
            "View",
            ["📋 Overview", "📈 Performance", "🔬 Explainability",
             "🤖 AI Insights", "🎯 What-If Scorer"],
            index=0,
        )

        st.markdown("### Filters")
        source_options = sorted(df["source"].dropna().unique())
        selected_sources = st.multiselect(
            "Lead Source",
            source_options,
            default=source_options,
            help="Select one or more lead sources to filter the analysis.",
        )

        group_options = sorted(df["source_group"].dropna().unique())
        selected_groups = st.multiselect(
            "Source Group",
            group_options,
            default=group_options,
        )

        owner_query = st.text_input(
            "Lead Owner (search)",
            placeholder="e.g. Alice",
            help="Case-insensitive substring match on lead owner name.",
        )

        st.markdown("---")
        st.caption(
            f"Data: `{DATA_PATH.name}`  \n"
            f"Model: `{MODEL_PATH.name}`  \n"
            f"Streamlit {st.__version__}"
        )

    owner_mask = (
        df["lead_owner"].astype(str).str.contains(owner_query, case=False, na=False)
        if owner_query
        else pd.Series(True, index=df.index)
    )

    filtered = df[
        df["source"].isin(selected_sources)
        & df["source_group"].isin(selected_groups)
        & owner_mask
    ].copy()

    return view, filtered


