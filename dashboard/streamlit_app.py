# KPI Cards
# ---------------------------------------------------------------------------
def render_kpis(full_df: pd.DataFrame, filtered: pd.DataFrame):
    total_all   = len(full_df)
    total_filt  = len(filtered)
    rate_all    = full_df["is_won"].mean()
    rate_filt   = filtered["is_won"].mean() if total_filt else 0.0

    src_counts  = filtered["source"].value_counts()
    top_src     = src_counts.idxmax() if not src_counts.empty else "—"
    top_src_n   = int(src_counts.max()) if not src_counts.empty else 0
    top_src_rate= (
        filtered[filtered["source"] == top_src]["is_won"].mean()
        if top_src != "—" else 0.0
    )

    grp_counts  = filtered["source_group"].value_counts()
    top_group   = grp_counts.idxmax() if not grp_counts.empty else "—"

    c1, c2, c3, c4 = st.columns(4)
    c1.metric(
        "Total Leads (filtered)",
        f"{total_filt:,}",
        delta=f"{total_filt - total_all:+,} vs all" if total_filt != total_all else None,
    )
    c2.metric(
        "Conversion Rate",
        f"{rate_filt * 100:.2f}%",
        delta=f"{(rate_filt - rate_all) * 100:+.2f} pp vs all"
              if total_filt != total_all else None,
        delta_color="normal",
    )
    c3.metric(
        "Top Source",
        top_src,
        delta=f"{top_src_rate * 100:.1f}% win rate  ·  {top_src_n:,} leads",
        delta_color="off",
    )
    c4.metric(
        "Top Source Group",
        top_group,
        delta=f"{int(grp_counts.max()):,} leads" if not grp_counts.empty else None,
        delta_color="off",
    )


