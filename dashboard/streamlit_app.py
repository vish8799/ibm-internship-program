def main():
    # Load data (cached)
    try:
        df = load_data()
    except (FileNotFoundError, ValueError) as err:
        st.error(f"**Data load failed:** {err}")
        st.stop()

    view, filtered = render_sidebar(df)

    st.title("📊 Lead Intelligence Dashboard")
    st.caption(
        "All metrics computed dynamically from `data/processed/cleaned_leads.csv` "
        "and `models/best_model.pkl` (Phase 5 pipeline)."
    )

    if filtered.empty:
        st.warning("⚠️ No records match the current filters. Adjust the sidebar selections.")
        return

    # KPI cards always visible
    render_kpis(df, filtered)
    st.markdown("---")

    # Route to selected view
    view_key = view.split(" ", 1)[1]  # strip emoji prefix
    if view_key == "Overview":
        render_overview(filtered)
    elif view_key == "Performance":
        render_performance(filtered)
    elif view_key == "Explainability":
        render_explainability()
    elif view_key == "AI Insights":
        render_ai_insights()
    else:
        render_scorer(df)


if __name__ == "__main__":
    main()
