def render_performance(filtered: pd.DataFrame):
    st.markdown("## 📈 Source & Channel Performance")

    # Source group summary
    grp = (
        filtered.groupby("source_group", as_index=False)
        .agg(Leads=("source_group", "size"), Won=("is_won", "sum"))
    )
    grp["Win Rate %"] = (grp["Won"] / grp["Leads"] * 100).round(2)
    grp = grp.sort_values("Win Rate %", ascending=False)

    col1, col2 = st.columns(2)
    with col1:
        st.markdown("### Source Group Win Rate")
        fig_grp = go.Figure(go.Bar(
            x=grp["source_group"], y=grp["Win Rate %"],
            marker_color=CLR_PURPLE,
            text=grp["Win Rate %"].apply(lambda v: f"{v:.2f}%"),
            textposition="outside",
        ))
        fig_grp.update_layout(
            height=320, plot_bgcolor=CLR_BG, paper_bgcolor="white",
            margin=dict(l=0, r=0, t=10, b=10),
            yaxis_title="Win Rate (%)", xaxis_title="Source Group",
        )
        st.plotly_chart(fig_grp, use_container_width=True)

    with col2:
        st.markdown("### Source Group Volume")
        fig_vol = go.Figure(go.Bar(
            x=grp["source_group"], y=grp["Leads"],
            marker_color=CLR_BLUE,
            text=grp["Leads"].apply(lambda v: f"{v:,}"),
            textposition="outside",
        ))
        fig_vol.update_layout(
            height=320, plot_bgcolor=CLR_BG, paper_bgcolor="white",
            margin=dict(l=0, r=0, t=10, b=10),
            yaxis_title="Leads", xaxis_title="Source Group",
        )
        st.plotly_chart(fig_vol, use_container_width=True)

    # Full source×group heatmap (all sources in filtered data)
    st.markdown("### Source × Source Group Win Rate Heatmap")
    pivot = (
        filtered.pivot_table(
            index="source_group", columns="source",
            values="is_won", aggfunc="mean"
        ) * 100
    ).round(2)

    fig_heat = px.imshow(
        pivot,
        text_auto=".1f",
        color_continuous_scale=[[0, "#fef9c3"], [0.5, CLR_BLUE], [1, CLR_GREEN]],
        labels=dict(x="Source", y="Source Group", color="Win Rate (%)"),
        aspect="auto",
    )
    fig_heat.update_layout(
        height=260,
        margin=dict(l=0, r=0, t=10, b=10),
        paper_bgcolor="white",
    )
    st.plotly_chart(fig_heat, use_container_width=True)

    # Won vs Not-Won stacked bar by source
    st.markdown("### Won / Not-Won Stacked Bar by Source")
    src_stack = (
        filtered.groupby(["source", "is_won"], as_index=False)
        .size()
        .rename(columns={"size": "Count"})
    )
    src_stack["Outcome"] = src_stack["is_won"].map({1: "Won", 0: "Not Won"})
    src_order = (
        filtered.groupby("source")["is_won"].mean()
        .sort_values(ascending=False).index.tolist()
    )
    fig_stack = px.bar(
        src_stack,
        x="source", y="Count", color="Outcome",
        color_discrete_map={"Won": CLR_GREEN, "Not Won": CLR_RED},
        category_orders={"source": src_order},
        barmode="stack",
        labels={"source": "Lead Source", "Count": "Lead Count"},
    )
    fig_stack.update_layout(
        height=340, plot_bgcolor=CLR_BG, paper_bgcolor="white",
        margin=dict(l=0, r=0, t=10, b=10),
        xaxis_tickangle=-35,
    )
    st.plotly_chart(fig_stack, use_container_width=True)

    # Summary table
    st.markdown("### Full Source Summary Table")
    src_tbl = (
        filtered.groupby("source", as_index=False)
        .agg(
            Leads=("source", "size"),
            Won=("is_won", "sum"),
        )
    )
    src_tbl["Win Rate %"] = (src_tbl["Won"] / src_tbl["Leads"] * 100).round(2)
    src_tbl["Lost"]       = src_tbl["Leads"] - src_tbl["Won"]
    src_tbl["Tier"]       = src_tbl["source"].map(SOURCE_TIER)
    src_tbl = src_tbl.sort_values("Win Rate %", ascending=False).reset_index(drop=True)
    st.dataframe(
        src_tbl[["source", "Tier", "Leads", "Won", "Lost", "Win Rate %"]],
        use_container_width=True, hide_index=True,
    )


